(function () {
  var SUPPORTED = ['en', 'it', 'es'];
  var STORAGE_KEY = 'cv-lang';

  function pickInitialLanguage() {
    try {
      var saved = window.localStorage.getItem(STORAGE_KEY);
      if (saved && SUPPORTED.indexOf(saved) !== -1) return saved;
    } catch (e) { /* localStorage unavailable (private mode) */ }

    var nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return SUPPORTED.indexOf(nav) !== -1 ? nav : 'en';
  }

  function applyLanguage(lang) {
    var dict = TRANSLATIONS[lang];
    if (!dict) return;

    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute('data-i18n');
      if (dict[key] !== undefined) nodes[i].innerHTML = dict[key];
    }

    document.documentElement.lang = lang;

    var desc = document.querySelector('meta[name="description"]');
    if (desc && dict['meta.description']) desc.setAttribute('content', dict['meta.description']);

    var buttons = document.querySelectorAll('.cc-lang-switch button');
    for (var j = 0; j < buttons.length; j++) {
      var isActive = buttons[j].getAttribute('data-lang') === lang;
      buttons[j].classList.toggle('active', isActive);
      buttons[j].setAttribute('aria-pressed', isActive ? 'true' : 'false');
    }

    try { window.localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* ignore */ }
  }

  function init() {
    var switcher = document.querySelector('.cc-lang-switch');
    if (switcher) {
      switcher.addEventListener('click', function (event) {
        var button = event.target.closest('button[data-lang]');
        if (button) applyLanguage(button.getAttribute('data-lang'));
      });
    }
    applyLanguage(pickInitialLanguage());
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
